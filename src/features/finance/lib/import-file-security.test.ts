import { afterEach, describe, expect, it, vi } from 'vitest'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import * as XLSX from 'xlsx'
import { strToU8, zipSync } from 'fflate'
import { checkWorkbookContainer, decodeCsvBuffer, IMPORT_LIMITS, parseCSV, parseXLSX } from './import-file-parser'
import { parseFile } from './import-file-reader'
import { ImportTestWorker } from './import-worker.test-helper'
import { downloadTemplate, generatePreview, guessColumnMapping, TEMPLATE_COLUMNS } from './import-utils'
import { exportData, STATEMENT_COLUMNS } from './export-utils'

function workbook(rows: unknown[][], bookType: 'xlsx' | 'biff8' = 'xlsx', mutate?: (sheet: XLSX.WorkSheet) => void) {
  const sheet = XLSX.utils.aoa_to_sheet(rows)
  mutate?.(sheet)
  const wb = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(wb, sheet, 'Dados')
  return XLSX.write(wb, { bookType, type: 'array', compression: true }) as ArrayBuffer
}
const headers = ['Data', 'Descrição', 'Valor', 'Tipo']
const data = [46023, 'Receita fictícia', 1234.56, 'AJUSTE']
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.useRealTimers() })

describe('CC22 parser compatibility and hostile files', () => {
  for (const extension of ['xls', 'xlsx', 'biff5']) {
    it(`matches the old parser output for a synthetic ${extension} fixture generated by 0.18.5`, () => {
      const root = path.resolve('e2e/fixtures')
      const file = extension === 'biff5' ? 'finance-cc22-legacy-biff5.xls' : `finance-cc22-legacy.${extension}`
      const buffer = Uint8Array.from(readFileSync(path.join(root, file))).buffer
      const expected = JSON.parse(readFileSync(path.join(root, `finance-cc22-legacy-${extension}.json`), 'utf8'))
      expect(expected.generatorVersion).toBe('0.18.5')
      expect(JSON.parse(JSON.stringify(parseXLSX(buffer)))).toEqual({ headers: expected.headers, rows: expected.rows })
    })
  }
  for (const format of ['xlsx', 'biff8'] as const) {
    it(`preserves ${format} dates, BRL numbers and empty cells`, () => {
      const parsed = parseXLSX(workbook([...[[...headers, 'Observação']], [...data, null]], format))
      expect(parsed.headers).toEqual([...headers, 'Observação'])
      expect(parsed.rows[0].Observação).toBeNull()
      const preview = generatePreview(parsed.headers, parsed.rows, guessColumnMapping(parsed.headers), 'CC22-synthetic')
      expect(preview.rows[0].mapped.transaction_date).toBe('2026-01-01')
      expect(preview.rows[0].mapped.amount).toBe(1234.56)
      expect(preview.rows[0].valid).toBe(true)
    })
  }
  it('preserves CSV delimiters, accents, quoting and BRL strings', () => {
    const parsed = parseCSV('\ufeffData;Descrição;Valor;Tipo\r\n01/01/2026;"Texto; com aspas";1.234,56;AJUSTE\r\n')
    expect(parsed.headers).toEqual(headers)
    expect(parsed.rows[0].Valor).toBe('1.234,56')
    expect(parsed.rows[0].Descrição).toBe('Texto; com aspas')
  })
  it('preserves empty/header-only CSV behavior', () => {
    expect(parseCSV('')).toEqual({ headers: [], rows: [] })
    expect(parseCSV('Data;Valor\n').rows).toEqual([])
  })
  it('keeps Windows-1252 and UTF-16 BOM decoding', () => {
    expect(decodeCsvBuffer(new Uint8Array([0xe7]).buffer)).toBe('ç')
    expect(decodeCsvBuffer(new Uint8Array([255, 254, 65, 0]).buffer)).toBe('A')
    expect(decodeCsvBuffer(new Uint8Array([254, 255, 0, 65]).buffer)).toBe('A')
  })
  it('uses first populated sheet when an empty sheet precedes it', () => {
    const wb = XLSX.utils.book_new()
    XLSX.utils.book_append_sheet(wb, {}, 'Vazia')
    XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([headers, data]), 'Dados')
    expect(parseXLSX(XLSX.write(wb, { type: 'array', bookType: 'xlsx' })).rows[0].Valor).toBe(1234.56)
  })
  it('accepts a valid empty workbook without manufacturing financial rows', () => {
    expect(parseXLSX(workbook([])).rows).toEqual([])
  })
  it('rejects empty, corrupt and HTML-disguised workbooks', () => {
    for (const bytes of [new ArrayBuffer(0), new Uint8Array([1, 2, 3]).buffer, new TextEncoder().encode('<html>not a workbook</html>').buffer]) {
      expect(() => parseXLSX(bytes)).toThrow(/inválido ou corrompido/)
    }
  })
  it('rejects a truncated OOXML ZIP', () => {
    const bytes = workbook([headers, data])
    expect(() => parseXLSX(bytes.slice(0, -30))).toThrow(/inválido ou corrompido/)
  })
  it('rejects input over 10 MiB before parsing', () => {
    expect(() => parseXLSX(new ArrayBuffer(IMPORT_LIMITS.fileBytes + 1))).toThrow(/10 MB/)
    expect(() => parseCSV('a'.repeat(IMPORT_LIMITS.fileBytes + 1))).toThrow(/10 MB/)
  })
  it('rejects overlong cells', () => {
    expect(() => parseCSV('Descrição\n' + 'a'.repeat(IMPORT_LIMITS.cellCharacters + 1))).toThrow(/32767/)
  })
  it('rejects excess CSV lines without returning a truncated import', () => {
    expect(() => parseCSV('Valor\n' + '1\n'.repeat(IMPORT_LIMITS.rows + 1))).toThrow(/10000 linhas/)
  })
  it('rejects declared worksheet row overflow', () => {
    expect(() => parseXLSX(workbook([['Valor'], [1]], 'xlsx', sheet => { sheet['!ref'] = 'A1:A10002' }))).toThrow(/10000 linhas/)
    expect(() => parseXLSX(workbook([], 'xlsx', sheet => {
      sheet.A10003 = { t: 's', v: 'Valor' }; sheet.A10004 = { t: 'n', v: 1 }; sheet['!ref'] = 'A10003:A10004'
    }))).toThrow(/10000 linhas/)
  })
  it('rejects excess XLSX and CSV columns', () => {
    const columns = Array.from({ length: IMPORT_LIMITS.columns + 1 }, (_, i) => 'C' + i)
    expect(() => parseCSV(columns.join(';') + '\n' + columns.join(';'))).toThrow(/100 colunas/)
    expect(() => parseXLSX(workbook([columns, columns]))).toThrow(/100 colunas/)
  })
  it('rejects excessive worksheet cell area', () => {
    expect(() => parseXLSX(workbook([['Valor'], [1]], 'xlsx', sheet => { sheet['!ref'] = 'A1:CV3002' }))).toThrow(/250000 células/)
  })
  for (const key of ['__proto__', 'prototype', 'constructor', ' Constructor ']) {
    it(`rejects dangerous header ${key} before object projection`, () => {
      expect(() => parseCSV(`${key};Valor\nvalor;1`)).toThrow(/Cabeçalho inseguro/)
      expect(() => parseXLSX(workbook([[key, 'Valor'], ['valor', 1]]))).toThrow(/Cabeçalho inseguro/)
      expect(Object.prototype).not.toHaveProperty('polluted')
    })
  }
  it('allows dangerous-looking text as a value, never as a property', () => {
    const row = parseCSV('Descrição;Valor\n__proto__;1').rows[0]
    expect(row.Descrição).toBe('__proto__')
    expect(Object.getPrototypeOf(row)).toBeNull()
  })
  it('keeps unknown headers available for manual mapping', () => {
    const parsed = parseXLSX(workbook([['Campo personalizado', 'Valor', 'Revisado'], ['X', 20, true]]))
    expect(parsed.headers).toEqual(['Campo personalizado', 'Valor', 'Revisado'])
    expect(parsed.rows[0]['Campo personalizado']).toBe('X')
    expect(parsed.rows[0].Revisado).toBe(true)
  })
  it('preserves invalid date and money row validation without silently persisting', () => {
    const parsed = parseCSV('Data;Descrição;Valor;Tipo\nontem;Teste;dinheiro;AJUSTE')
    const preview = generatePreview(parsed.headers, parsed.rows, guessColumnMapping(parsed.headers), 'CC22-invalid')
    expect(preview.rows[0].valid).toBe(false)
    expect(preview.rows[0].errors.join(' ')).toMatch(/data/i)
    expect(preview.rows[0].errors.join(' ')).toMatch(/valor/i)
  })
  it('does not evaluate formulas, execute HTML or request hyperlink targets', () => {
    const parsed = parseXLSX(workbook([['Descrição', 'Valor'], ['<script>globalThis.CC22=true</script>', 1]], 'xlsx', sheet => {
      sheet.B2 = { t: 'n', v: 1, f: '1+1' }
      sheet.A2.l = { Target: 'https://example.invalid/no-network' }
    }))
    expect(parsed.rows[0].Valor).toBe(1)
    expect(parsed.rows[0].Descrição).toContain('<script>')
    expect(globalThis).not.toHaveProperty('CC22')
  })
  it('rejects ZIP expansion bombs from metadata before decompression', () => {
    const buffer = workbook([headers, data]), view = new DataView(buffer)
    for (let i = 0; i < buffer.byteLength - 46; i++) {
      if (view.getUint32(i, true) === 0x02014b50) { view.setUint32(i + 24, IMPORT_LIMITS.expandedBytes + 1, true); break }
    }
    expect(() => checkWorkbookContainer(buffer)).toThrow(/descompressão segura/)
  })
  it('bounds real inflation even when both ZIP size fields lie', () => {
    const bytes = zipSync({ '[Content_Types].xml': strToU8('A'.repeat(150000)), 'xl/workbook.xml': strToU8('x') })
    const buffer = Uint8Array.from(bytes).buffer, view = new DataView(buffer)
    view.setUint32(22, 1, true)
    for (let i = 0; i < buffer.byteLength - 46; i++) {
      if (view.getUint32(i, true) === 0x02014b50) { view.setUint32(i + 24, 1, true); break }
    }
    expect(() => checkWorkbookContainer(buffer)).toThrow(/descompressão segura/)
  })
  it('rejects a ZIP with a corrupt CRC rather than importing altered values', () => {
    const buffer = workbook([headers, data]), view = new DataView(buffer)
    for (let i = 0; i < buffer.byteLength - 46; i++) {
      if (view.getUint32(i, true) === 0x02014b50) { view.setUint32(i + 16, 123, true); break }
    }
    expect(() => parseXLSX(buffer)).toThrow(/inválido ou corrompido/)
  })
  for (const name of ['xl/vbaProject.bin', 'xl/macrosheets/sheet1.xml', 'xl/externalLinks/externalLink1.xml']) {
    it(`rejects active-content container entry ${name}`, () => {
      const bytes = zipSync({ '[Content_Types].xml': strToU8('x'), 'xl/workbook.xml': strToU8('x'), [name]: strToU8('synthetic') })
      expect(() => checkWorkbookContainer(Uint8Array.from(bytes).buffer)).toThrow(/macros ou vínculos externos/)
    })
  }
  it('rejects malformed quoted CSV instead of swallowing parser errors', () => {
    expect(() => parseCSV('Descrição;Valor\n"sem fechamento;1')).toThrow(/CSV inválido/)
  })
  for (const kind of ['template', 'export']) {
    it(`round-trips the existing ${kind} XLSX download without changing financial writer code`, async () => {
      let blob: Blob | undefined
      vi.stubGlobal('URL', { createObjectURL(value: Blob) { blob = value; return 'blob:cc22' }, revokeObjectURL() {} })
      vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
      if (kind === 'template') downloadTemplate('xlsx')
      else exportData([{ label: 'CC22 sintético', amount: 1234.56 }], STATEMENT_COLUMNS, 'CC22', 'xlsx')
      expect(blob).toBeDefined()
      const buffer = await new Promise<ArrayBuffer>((resolve, reject) => {
        const reader = new FileReader(); reader.onload = () => resolve(reader.result as ArrayBuffer); reader.onerror = reject; reader.readAsArrayBuffer(blob!)
      })
      const parsed = parseXLSX(buffer)
      if (kind === 'template') { expect(parsed.headers).toEqual(TEMPLATE_COLUMNS); expect(parsed.rows).toHaveLength(3); expect(parsed.rows[0].Valor).toBe('1500,00') }
      else { expect(parsed.rows[0].Descrição).toBe('CC22 sintético'); expect(String(parsed.rows[0].Valor)).toContain('1.234,56') }
    })
  }
})

describe('CC22 file reader lifecycle', () => {
  it('reads CSV through the isolated worker protocol', async () => {
    vi.stubGlobal('Worker', ImportTestWorker)
    const parsed = await parseFile(new File(['Valor\n1'], 'dados.CSV'))
    expect(parsed.fileType).toBe('csv')
    expect(parsed.rows[0].Valor).toBe('1')
  })
  it('rejects incompatible extensions with the existing message', async () => {
    await expect(parseFile(new File(['x'], 'file.exe'))).rejects.toThrow('Unsupported file type. Use CSV, XLS or XLSX.')
  })
  it('rejects large files before allocating a worker', async () => {
    const makeWorker = vi.fn()
    vi.stubGlobal('Worker', makeWorker)
    await expect(parseFile(new File([new Uint8Array(IMPORT_LIMITS.fileBytes + 1)], 'large.xlsx'))).rejects.toThrow(/10 MB/)
    expect(makeWorker).not.toHaveBeenCalled()
  })
  it('rejects worker-less browsers without falling back to blocking parsing', async () => {
    vi.stubGlobal('Worker', undefined)
    await expect(parseFile(new File(['x'], 'test.csv'))).rejects.toThrow(/segundo plano/)
  })
  it('terminates a stalled worker, rejects concurrent parsing and permits retry', async () => {
    vi.useFakeTimers()
    const terminate = vi.fn(), abort = vi.fn()
    class StalledWorker { terminate = terminate; postMessage() {} }
    class StalledReader { static LOADING = 1; readyState = 1; abort = abort; readAsArrayBuffer() {} }
    vi.stubGlobal('Worker', StalledWorker)
    vi.stubGlobal('FileReader', StalledReader)
    const pending = parseFile(new File(['x'], 'test.xlsx'))
    const rejected = expect(pending).rejects.toThrow(/Tempo limite/)
    await expect(parseFile(new File(['x'], 'second.xlsx'))).rejects.toThrow(/Aguarde/)
    await vi.advanceTimersByTimeAsync(IMPORT_LIMITS.timeoutMs)
    await rejected
    expect(terminate).toHaveBeenCalledOnce()
    expect(abort).toHaveBeenCalledOnce()
    vi.useRealTimers(); vi.unstubAllGlobals(); vi.stubGlobal('Worker', ImportTestWorker)
    expect((await parseFile(new File(['Valor\n1'], 'retry.csv'))).rows[0].Valor).toBe('1')
  })
})
